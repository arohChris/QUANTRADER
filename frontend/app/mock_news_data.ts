// WHY: mock news data for the Overview news section.
//
//   NewsItem    -> financial_analyst_app/shared/contracts/news.py (new, M2.12)
//   NewsSnapshot -> same
//   licence rule -> docs/specs/m2.12_news_ingest.spec.md, "Sources and what we may reproduce"
//
// THE VALUES ARE EMPTY, AND THAT IS THE POINT. The previous version of this section
// rendered invented headlines ("Momentum improving", "Dollar steadies before the next data
// window") with nothing behind them. Those are gone and must not come back: a headline
// that no feed produced is a fabricated claim, and it is indistinguishable from a real one
// once it is on screen.
//
// Until `GET /api/v1/news` exists, the section renders an explicit "not connected" state.
// The first real headlines arrive when M2.12 lands, and they will carry their publisher,
// their published time, and — for copyrighted sources — a link instead of the text.

export type NewsCategory =
  | "monetary_policy"
  | "macro"
  | "regulation"
  | "market"
  | "research";

export type NewsStatus = "fresh" | "stale" | "degraded" | "unavailable";

export type SourceHealth = "ok" | "failed" | "stale";

export type NewsItem = {
  item_id: string;
  source_id: string;
  publisher: string;
  category: NewsCategory;
  // Empty string when the source is link-only: see the licence note below.
  title: string;
  url: string;
  published_at: string;
  availability_time: string;
  reference_snapshot_id: string | null;
  redistribute_text: boolean;
  summary: string | null;
  // Optional per-item image. Most institutional feeds ship a media enclosure; many items
  // legitimately have none, so `null` is a supported state and is never faked with "".
  // `image_alt` is REQUIRED whenever `image_url` is set: an <img> with no alt is
  // unreadable for a screen reader. Never a placeholder like "image".
  image_url: string | null;
  image_alt: string | null;
  // True when `summary` was cut at the word boundary. The UI may then say "summary
  // truncated" rather than implying the text is complete.
  summary_truncated: boolean;
};

export type NewsSnapshot = {
  status: NewsStatus;
  items: NewsItem[];
  as_of: string;
  source_health: Record<string, SourceHealth>;
  last_good_at: string | null;
  // Provenance of the payload itself, so a reader of the file knows where it came from.
  generated_by?: string;
  note?: string;
};

// Fail closed. A source whose licence class is unknown may NOT have its text reproduced,
// so the absence of a flag must never be read as permission. m2.12 spec edge 17.
export const DEFAULT_REDISTRIBUTE_TEXT = false;


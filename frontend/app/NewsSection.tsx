// News section for the Overview.
//
// WHY it can be empty: the previous version of this panel rendered invented headlines.
// Those are gone. This section shows real headlines when `GET /api/v1/news` exists, and
// until then says plainly that it has none — because a headline no feed produced is a
// fabricated claim, and on screen it is indistinguishable from a real one.
//
// Two behaviours the spec pins:
//   * No network from here. The browser does not fetch; the backend serves, or it does not.
//   * Licence. A source may carry `redistribute_text: false` (a copyrighted publisher),
//     in which case we show the publisher and a link and never the text.
import { useState } from "react";
import { ExternalLink, Newspaper, Rss } from "lucide-react";
import { NEWS_SOURCES_PLANNED, NEWS_UNAVAILABLE_REASON, type NewsItem, type NewsSnapshot } from "./mock_news_data";
// Generated by financial_analyst_app/scripts/verify_m2.12_news_snapshot.py from the
// open-licence feeds. Typed, so `tsc` rejects a malformed payload at build time.
import { NEWS_SNAPSHOT } from "./news_snapshot.generated";
import { Note } from "./surface_ui";

function relativeTime(iso: string, now: Date): string {
  const then = new Date(iso).getTime();
  const minutes = Math.max(0, Math.round((now.getTime() - then) / 60000));
  if (minutes < 60) {
    return `${minutes}m ago`;
  }
  const hours = Math.round(minutes / 60);
  if (hours < 24) {
    return `${hours}h ago`;
  }
  return `${Math.round(hours / 24)}d ago`;
}

function NewsRow({ item, now }: { item: NewsItem; now: Date }) {
  // An image is copyrighted exactly like a headline, so it rides the SAME licence flag as
  // the text. A link-only source gets no image rendered here.
  const thumb = item.redistribute_text && item.image_url && item.image_alt ? item.image_url : null;
  const [thumbFailed, setThumbFailed] = useState(false);

  return (
    <li className={thumb && !thumbFailed ? "news-item has-thumb" : "news-item"}>
      {thumb && !thumbFailed ? (
        <img
          className="news-thumb"
          src={thumb}
          // Required and never empty: the image carries the item's meaning, so a
          // decorative empty alt would hide it from a screen reader.
          alt={item.image_alt as string}
          loading="lazy"
          onError={() => setThumbFailed(true)}
        />
      ) : thumb ? (
        // Broken image: collapse to text rather than leave a torn gap in the list.
        <span className="news-thumb is-missing" aria-hidden="true" />
      ) : null}
      <span className="news-publisher">{item.publisher}</span>
      {item.redistribute_text ? (
        <a className="news-title" href={item.url} target="_blank" rel="noopener noreferrer">
          {item.title}
        </a>
      ) : (
        // Link-only source: we name the publisher and link out, and do not reproduce
        // copyrighted text (m2.12 spec, "Sources and what we may reproduce").
        <a className="news-title is-link-only" href={item.url} target="_blank" rel="noopener noreferrer">
          Read at {item.publisher} <ExternalLink size={11} />
        </a>
      )}
      <span className="news-meta mono">
        {item.category.replace("_", " ")} · {relativeTime(item.published_at, now)}
      </span>
    </li>
  );
}

export default function NewsSection({ snapshot = NEWS_SNAPSHOT, now = new Date() }: { snapshot?: NewsSnapshot; now?: Date }) {
  const failed = Object.entries(snapshot.source_health).filter(([, health]) => health === "failed");
  const open = snapshot.items.filter((item) => item.redistribute_text);
  const linked = snapshot.items.filter((item) => !item.redistribute_text);
  // The panel shows a maximum of 10 headlines, newest first (human directive 2026-09-27).
  // The snapshot carries more than that, so this is a presentation cap — the ordering is
  // by published_at across all sources, so the ten shown span publishers rather than
  // being ten rows from whichever feed happens to be busiest.
  const MAX_VISIBLE = 10;
  const shown = open.slice(0, MAX_VISIBLE);

  return (
    <section className="panel news-panel" aria-label="News">
      <h2>News</h2>

      {snapshot.status === "unavailable" ? (
        <>
          <p className="news-empty">
            <Rss size={16} />
            No feed connected.
          </p>
          <Note>{NEWS_UNAVAILABLE_REASON}</Note>
        </>
      ) : (
        <>
          {snapshot.status !== "fresh" ? (
            // A stale or partial snapshot is labelled with its age. A silently missing
            // section would read as a quiet news day, which is a different claim.
            <p className="news-stale">
              {snapshot.status} · as of {new Date(snapshot.as_of).toISOString().slice(0, 16).replace("T", " ")} UTC
              {failed.length > 0 ? ` · ${failed.map(([id]) => id).join(", ")} failed` : ""}
            </p>
          ) : null}

          {snapshot.items.length === 0 ? (
            <p className="news-empty">No items from the connected feeds.</p>
          ) : (
            <>
              <ul className="news-list">
                {shown.map((item) => (
                  <NewsRow item={item} key={item.item_id} now={now} />
                ))}
              </ul>
              {open.length > MAX_VISIBLE ? (
                <p className="muted news-count">
                  Showing the {MAX_VISIBLE} most recent of {open.length}. Older releases stay in the
                  snapshot.
                </p>
              ) : null}
            </>
          )}

          {linked.length > 0 ? (
            <ul className="news-list is-linked">
              {linked.map((item) => (
                <NewsRow item={item} key={item.item_id} now={now} />
              ))}
            </ul>
          ) : null}
        </>
      )}

      {snapshot.status === "unavailable" ? (
        <details className="news-sources">
          <summary>
            <Newspaper size={12} />
            {NEWS_SOURCES_PLANNED.length} sources wired for M2.12
          </summary>
          <ul>
            {NEWS_SOURCES_PLANNED.map((source) => (
              <li key={source.id}>
                <span>{source.publisher}</span>
                <span className="muted">{source.redistribute_text ? "open licence" : "link only"}</span>
              </li>
            ))}
          </ul>
        </details>
      ) : null}
    </section>
  );
}
